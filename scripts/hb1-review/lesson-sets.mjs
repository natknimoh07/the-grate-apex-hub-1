// Copies the quizzes of the HB1 lessons written in the app (src/data/hb1-lessons/) into
// their course's question bank, one set per lesson (id "ls-<quizId>"), so practice,
// review, Apex and battles find them. Idempotent: replaces its own sets.
//
//   node --import ./tests/register.mjs scripts/hb1-review/lesson-sets.mjs
//
// It also writes src/data/hb1-lessons/practice-ids.ts: every question each lesson practises
// (its quiz, plus `pastSets`, `pastTopics` and `bankTopics` from the bank), so the lesson
// page shows the right count. Each question is practised by one lesson only (owner, 2026-11-14:
// a lesson's practice must be about that lesson; practice-owner.mjs picks the lesson when
// several claim the same question). Then rebuild the battle bank: node --import ./tests/register.mjs scripts/build-battle-bank.mjs
import { readFileSync, writeFileSync } from 'node:fs';

import { chooseOwners, lessonWords } from './practice-owner.mjs';

const practice = {};

const { HB1_LOCAL_LESSONS, hb1QuizQuestions } = await import('@/data/hb1-lessons');

const byCourse = new Map();
for (const lesson of HB1_LOCAL_LESSONS) {
  const course = lesson.id.split('-')[0];
  byCourse.set(course, [...(byCourse.get(course) ?? []), lesson]);
}

for (const [course, lessons] of byCourse) {
  const path = new URL(`../../public/curriculum/${course}.json`, import.meta.url);
  const bank = JSON.parse(readFileSync(path, 'utf8'));
  const ours = new Set(lessons.map((lesson) => `ls-${lesson.quizId}`));
  const sets = lessons.map((lesson) => ({
    id: `ls-${lesson.quizId}`,
    name: lesson.quizName,
    questions: hb1QuizQuestions(lesson).map((question) => ({ ...question, src: lesson.source })),
  }));
  // Lesson quizzes sit after the course's other quizzes, before its past papers.
  // Lesson sets no longer in use (a lesson split or renamed) are dropped too.
  const kept = bank.sets.filter((set) => !ours.has(set.id) && !set.id.startsWith('ls-'));
  const firstPaper = kept.findIndex((set) => /^Past Questions|^Predicted/i.test(set.name));
  const at = firstPaper < 0 ? kept.length : firstPaper;
  bank.sets = [...kept.slice(0, at), ...sets, ...kept.slice(at)];
  writeFileSync(path, JSON.stringify(bank));
  const claimed = new Map();
  const ownQuiz = new Map();
  for (const lesson of lessons) {
    const sets = new Set([`ls-${lesson.quizId}`, ...(lesson.pastSets ?? [])]);
    const topics = new Set(lesson.pastTopics ?? []);
    const labels = new Set(lesson.bankTopics ?? []);
    const ids = new Set();
    for (const set of bank.sets) for (const q of set.questions) if (sets.has(set.id) || (q.tp && topics.has(q.tp)) || labels.has(q.t) || labels.has(`${set.id}:${q.t}`)) ids.add(q.id);
    claimed.set(lesson.id, ids);
    for (const q of hb1QuizQuestions(lesson)) ownQuiz.set(q.id, lesson.id);
  }
  // A question practised by two or more lessons goes to one of them only (practice-owner.mjs);
  // a lesson's own quiz always stays with it.
  const claims = new Map();
  for (const [lessonId, ids] of claimed) for (const id of ids) if (!ownQuiz.has(id)) claims.set(id, new Set([...(claims.get(id) ?? []), lessonId]));
  const questions = new Map(bank.sets.flatMap((set) => set.questions.map((q) => [q.id, q])));
  const owners = chooseOwners(lessons.map((lesson) => ({ id: lesson.id, words: lessonWords(lesson) })), claims, questions);
  let shared = 0;
  for (const [lessonId, ids] of claimed) {
    practice[lessonId] = [...ids].filter((id) => (ownQuiz.has(id) ? ownQuiz.get(id) === lessonId : claims.get(id).size < 2 || owners.get(id) === lessonId));
  }
  for (const owner of owners.values()) if (owner) shared += 1;
  if (owners.size) console.log(`${course}: ${owners.size} questions claimed by 2+ lessons; ${shared} given to one lesson, ${owners.size - shared} to none`);
  console.log(course, sets.map((set) => `${set.name} (${set.questions.length})`).join(', '));
}

const file = new URL('../../src/data/hb1-lessons/practice-ids.ts', import.meta.url);
writeFileSync(file, `// Generated by scripts/hb1-review/lesson-sets.mjs — do not edit. Every question id each
// HB1 app lesson practises (its quiz, pastSets, pastTopics and bankTopics), each question in one lesson only.
export const HB1_PRACTICE_IDS: Record<string, string[]> = ${JSON.stringify(practice)};
`);
console.log('practice ids:', Object.entries(practice).map(([id, ids]) => `${id} ${ids.length}`).join(', '));
