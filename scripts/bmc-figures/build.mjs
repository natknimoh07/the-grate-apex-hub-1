// Builds the Basic Medical Chemistry pictures (public/images/bmc/*.svg) and their sizes
// (src/data/hb1-lessons/bmc-figures.ts). Run after changing a figure:
//   node scripts/bmc-figures/build.mjs [--sheet]     (--sheet also writes a contact sheet to view)
import { mkdirSync, writeFileSync } from 'node:fs';

import { svg } from './kit.mjs';

const LESSONS = ['alkanes', 'alkenes', 'aromatics', 'halides', 'carbonyl', 'amines-stereo'];

const root = new URL('../../', import.meta.url);
const outDir = new URL('public/images/bmc/', root);
mkdirSync(outDir, { recursive: true });

const figures = [];
for (const name of LESSONS) {
  const list = (await import(`./${name}.mjs`)).default;
  for (const figure of list) {
    if (figures.some((item) => item.id === figure.id)) throw new Error(`duplicate figure ${figure.id}`);
    writeFileSync(new URL(`${figure.id}.svg`, outDir), svg(figure.w, figure.h, figure.draw(), figure.title));
    figures.push(figure);
  }
}

const sizes = figures.map((f) => `  '${f.id}': [${f.w}, ${f.h}],`).join('\n');
writeFileSync(
  new URL('src/data/hb1-lessons/bmc-figures.ts', root),
  `// Generated by scripts/bmc-figures/build.mjs — do not edit by hand.\n// Each Basic Medical Chemistry picture in public/images/bmc/: [width, height].\nexport const BMC_FIGURES = {\n${sizes}\n} as const;\n\nexport type BmcFigureId = keyof typeof BMC_FIGURES;\n`,
);

// --sheet=<file.html>: one page showing the pictures (--only=<id prefix>), to look at them.
const sheet = process.argv.find((arg) => arg.startsWith('--sheet='))?.slice(8);
if (sheet) {
  const only = process.argv.find((arg) => arg.startsWith('--only='))?.slice(7);
  const shown = figures.filter((f) => !only || f.id.startsWith(only));
  const cells = shown.map((f) => `<div style="display:inline-block;margin:6px;vertical-align:top;font:12px Arial"><div>${f.id}</div><img src="${new URL(`${f.id}.svg`, outDir).href}" style="background:#f8f7f2;border:1px solid #ddd"></div>`).join('');
  writeFileSync(sheet, `<!doctype html><body style="margin:0;background:#fff">${cells}</body>`);
}
console.log(`${figures.length} figures written`);
